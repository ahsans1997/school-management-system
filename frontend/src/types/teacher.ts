import type { StoredDocument } from "@/types/document";

interface Ref {
  id: number;
  name: string;
}

/** A subject the teacher teaches in one section (e.g. Class 6 A — Mathematics). */
export interface TeachingAssignment {
  id: number;
  class: Ref;
  section: Ref;
  subject: Ref & { code: string | null };
}

export interface ClassTeacherOf {
  class: Ref;
  section: Ref;
}

export interface TeacherAccount {
  id: number;
  email: string;
  is_active: boolean;
}

export interface Teacher {
  id: number;
  employee_id: string;
  name: string;
  designation: string | null;
  department: string | null;
  qualification: string | null;
  joining_date: string;
  phone: string;
  /** Contact address — separate from the login email. */
  email: string | null;
  address: string | null;
  /** Decimal string, e.g. "32000.50". */
  salary: string | null;
  /** Expiring signed link, or null. */
  photo_url: string | null;
  account?: TeacherAccount | null;
  /** On list rows. */
  assignments_count?: number;
  /** On the profile. */
  assignments?: TeachingAssignment[];
  class_teacher_of?: ClassTeacherOf[];
  documents?: StoredDocument[];
  archived_at: string | null;
  created_at: string | null;
}

export interface TeacherInput {
  /** Blank on create → generated by the server ("T-0001"). */
  employee_id: string | null;
  name: string;
  designation: string | null;
  department: string | null;
  qualification: string | null;
  joining_date: string;
  phone: string;
  email: string | null;
  address: string | null;
  salary: string | null;
}
