import type { StoredDocument } from "@/types/document";
import type { Enrollment } from "@/types/enrollment";

export type Gender = "male" | "female" | "other";
export type BloodGroup =
  "A+" | "A-" | "B+" | "B-" | "AB+" | "AB-" | "O+" | "O-";
export type Relationship =
  | "father"
  | "mother"
  | "brother"
  | "sister"
  | "grandfather"
  | "grandmother"
  | "uncle"
  | "aunt"
  | "other";

/** A guardian as linked to a student (student_guardians). */
export interface GuardianLink {
  id: number;
  name: string;
  phone: string;
  relationship: Relationship;
  is_primary: boolean;
}

export interface Student {
  id: number;
  /** Public-facing ID (ID card, public result lookup). */
  student_id: string;
  admission_no: string;
  admission_date: string;
  name: string;
  dob: string;
  gender: Gender;
  blood_group: BloodGroup | null;
  father_name: string | null;
  mother_name: string | null;
  phone: string | null;
  address: string | null;
  previous_school: string | null;
  /** Expiring signed link, or null when there's no photo. */
  photo_url: string | null;
  /** On list rows. */
  primary_guardian?: GuardianLink | null;
  /** On the profile (show/update). Primary first. */
  guardians?: GuardianLink[];
  documents?: StoredDocument[];
  /** This year's enrollment (class/section/roll), on the list and profile. */
  current_enrollment?: Enrollment | null;
  /** Every year's enrollment, newest first (profile). */
  enrollments?: Enrollment[];
  archived_at: string | null;
  created_at: string | null;
}

export interface StudentInput {
  /** Blank on create → generated by the server. */
  student_id: string | null;
  admission_no: string | null;
  admission_date: string | null;
  name: string;
  dob: string;
  gender: Gender;
  blood_group: BloodGroup | null;
  father_name: string | null;
  mother_name: string | null;
  phone: string | null;
  address: string | null;
  previous_school: string | null;
}

